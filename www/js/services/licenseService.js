/* ============================================================
   LicenseService — fully offline product-key activation & expiry.

   Key format:  TS-<T><PPPPPP>-<SIGSIGSIG>
     T        = duration code: T (Trial/7 days), M (Month/30 days), L (Lifetime)
     PPPPPP   = 6-char random payload (unique per key, no meaning beyond that)
     SIGSIGSIG = first 8 hex chars of HMAC-SHA256(SECRET, T + PPPPPP)

   Keys are generated by the separate `keygen.js` dev tool (project
   root, never shipped inside www/ so it never ends up in the APK).
   That tool must use the exact same SECRET as here — see its header
   comment. Every valid key is verified purely by recomputing the
   HMAC, so no list of valid keys ever has to ship with the app.

   IMPORTANT HONESTY NOTE (kept here for future maintainers too):
   this whole scheme runs client-side inside the shipped WebView JS
   because the app must work with zero internet access. That means
   the SECRET below technically *can* be recovered by someone who
   unzips the APK and reads this file — there is no way to make an
   offline-only check unbreakable against a determined reverse
   engineer. What this buys you is a real deterrent against casual
   copying/resale (a fresh install always demands a valid key, and
   trial/month keys self-expire), not unbreakable DRM. True
   tamper-proof licensing would require a server round-trip, which
   conflicts with the "fully offline" requirement.
   ============================================================ */

const LicenseService = (function () {
  // Base64-encoded only to avoid the secret being plaintext-greppable
  // in the shipped bundle — NOT real security, see note above.
  const SECRET_B64 = 'VGFpbG9yU2hvcFBPUy1Tb290aG1lZGlhLUxpY2Vuc2UtU2VjcmV0LTIwMjYtdjE=';
  const SECRET = atob(SECRET_B64);

  const DURATIONS = {
    T: { days: 7, key: 'license.trial' },
    M: { days: 30, key: 'license.month' },
    L: { days: null, key: 'license.lifetime' }
  };

  const KEY_RE = /^TS-([TML])([A-Z0-9]{6})-([0-9A-F]{8})$/i;

  // In-memory cache populated by touch()/activate() so route changes
  // can check expiry synchronously without hitting the DB every time.
  let cache = { activated: false, durationCode: null, expiresAtMs: null, tampered: false };

  function bufToHex(buf) {
    return Array.from(new Uint8Array(buf)).map((b) => b.toString(16).padStart(2, '0')).join('');
  }

  async function hmacHex(message) {
    const enc = new TextEncoder();
    const cryptoKey = await crypto.subtle.importKey(
      'raw', enc.encode(SECRET), { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']
    );
    const sig = await crypto.subtle.sign('HMAC', cryptoKey, enc.encode(message));
    return bufToHex(sig);
  }

  function normalizeKey(raw) {
    return String(raw || '').trim().toUpperCase().replace(/\s+/g, '');
  }

  function parseKey(raw) {
    const m = normalizeKey(raw).match(KEY_RE);
    if (!m) return null;
    return { durationCode: m[1], payload: m[2], sig: m[3] };
  }

  async function verifyKey(raw) {
    const parsed = parseKey(raw);
    if (!parsed) return { ok: false };
    const expectedSig = (await hmacHex(parsed.durationCode + parsed.payload)).slice(0, 8).toUpperCase();
    if (expectedSig !== parsed.sig.toUpperCase()) return { ok: false };
    return { ok: true, durationCode: parsed.durationCode };
  }

  function computeExpiry(durationCode, activatedAtMs) {
    const days = DURATIONS[durationCode].days;
    return days == null ? null : activatedAtMs + days * 24 * 60 * 60 * 1000;
  }

  async function activate(rawKey) {
    const result = await verifyKey(rawKey);
    if (!result.ok) return { ok: false, error: 'invalid' };

    const now = Date.now();
    const expiresAtMs = computeExpiry(result.durationCode, now);
    await SettingsService.setMany({
      license_key: normalizeKey(rawKey),
      license_duration: result.durationCode,
      license_activated_at: String(now),
      license_expires_at: expiresAtMs == null ? '' : String(expiresAtMs),
      license_last_seen_at: String(now)
    });
    cache = { activated: true, durationCode: result.durationCode, expiresAtMs, tampered: false };
    return { ok: true };
  }

  // Called once at boot: loads stored license state into the cache and
  // runs the clock-rollback heuristic (if "now" is earlier than the
  // last time the app was ever seen, someone wound the clock back to
  // dodge expiry — treat that as tampering and block access).
  async function touch() {
    const durationCode = await SettingsService.get('license_duration', '');
    const expiresRaw = await SettingsService.get('license_expires_at', '');
    const lastSeenRaw = await SettingsService.get('license_last_seen_at', '');
    const now = Date.now();

    if (!durationCode) {
      cache = { activated: false, durationCode: null, expiresAtMs: null, tampered: false };
      return cache;
    }

    const lastSeenMs = lastSeenRaw ? parseInt(lastSeenRaw, 10) : now;
    // Only Trial/Month have an expiry a rolled-back clock could exploit —
    // a Lifetime key has nothing to gain from it, so never flag it as
    // tampered (avoids ever locking out a paid lifetime customer over a
    // harmless clock glitch, e.g. before the phone's first network time sync).
    const tampered = durationCode !== 'L' && now < lastSeenMs - (60 * 60 * 1000); // >1hr backward jump

    await SettingsService.set('license_last_seen_at', String(Math.max(now, lastSeenMs)));

    cache = {
      activated: true,
      durationCode,
      expiresAtMs: expiresRaw ? parseInt(expiresRaw, 10) : null,
      tampered
    };
    return cache;
  }

  function isValidCached() {
    if (!cache.activated) return false;
    if (cache.tampered) return false;
    if (cache.expiresAtMs != null && Date.now() > cache.expiresAtMs) return false;
    return true;
  }

  function getCachedStatus() {
    const expired = cache.activated && !cache.tampered && cache.expiresAtMs != null && Date.now() > cache.expiresAtMs;
    let daysLeft = null;
    if (cache.activated && cache.expiresAtMs != null) {
      daysLeft = Math.max(0, Math.ceil((cache.expiresAtMs - Date.now()) / (24 * 60 * 60 * 1000)));
    }
    return {
      activated: cache.activated,
      durationCode: cache.durationCode,
      durationLabelKey: cache.durationCode ? DURATIONS[cache.durationCode].key : null,
      expiresAtMs: cache.expiresAtMs,
      expired,
      tampered: cache.tampered,
      daysLeft,
      valid: isValidCached()
    };
  }

  return { activate, touch, isValidCached, getCachedStatus, parseKey };
})();
